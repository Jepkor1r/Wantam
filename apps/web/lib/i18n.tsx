type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (typeof copy)["en"];
};

const LangContext = createContext<Ctx | null>(null);

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("duka-lang");
    if (saved === "en" || saved === "sw") {
      setLangState(saved);
      document.documentElement.lang = saved === "sw" ? "sw" : "en";
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("duka-lang", l);
    document.documentElement.lang = l === "sw" ? "sw" : "en";
  }, []);

  const value = useMemo(
    () => ({ lang, setLang, t: copy[lang] }),
    [lang, setLang],
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang needs LangProvider");
  return ctx;
}
